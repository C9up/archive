/**
 * Signed-URL middleware for the Local storage driver.
 *
 * Verifies the HMAC produced by {@link LocalDriver.getSignedUrl} and,
 * on success, serves the file from the driver. Tampered signatures →
 * 403 `E_ARCHIVE_INVALID_SIGNATURE`. Expired `exp` → 403
 * `E_ARCHIVE_EXPIRED_SIGNATURE`. A valid signature for a file that is not
 * stored → 404 `E_ARCHIVE_NOT_FOUND`. Any other failure to serve a file is
 * thrown as `E_CANNOT_SERVE_FILE`, the failure as its `cause`.
 * No signature at all → the file's visibility decides: a public file is
 * served, a private one refused with 403 `E_ARCHIVE_ACCESS_DENIED`, and a
 * name that is not stored falls through to `next()`.
 *
 * @implements Story 43.2 AC 5
 */

import { createHmac, timingSafeEqual } from "node:crypto";
import {
	E_ARCHIVE_NOT_FOUND,
	E_ARCHIVE_PREFIX_MISMATCH,
	E_ARCHIVE_SIGNING_DISABLED,
	E_CANNOT_SERVE_FILE,
} from "./errors.js";
import { matchesIfNoneMatch } from "./etag.js";
import { isKeyRefusal, normalizeKey } from "./keys.js";
import {
	HEADER_OVERRIDES,
	type HeaderOverride,
	isHeaderValue,
	signedPayload,
} from "./local-signature.js";
import type {
	LocalDriver,
	Metadata,
	StorageManager,
} from "./StorageManager.js";

/**
 * Minimal request/response contract the signed-route handler needs.
 * Matches Ream's `HttpContext` structurally — the Ream HttpContext
 * naturally satisfies it via structural subtyping — but avoids
 * importing the concrete Ream type, which keeps the coupling light
 * and lets tests build plain-object mocks without double-casts.
 */
export interface SignedRouteResponse {
	status(code: number): SignedRouteResponse;
	header(name: string, value: string): SignedRouteResponse;
	/**
	 * Send a readable as the body. The framework's response streams it to
	 * the client; the file is never held in memory whole.
	 */
	stream(body: NodeJS.ReadableStream): Promise<void> | void;
	json(data: unknown): void;
}

export interface SignedRouteHttpContext {
	request: {
		method(): string;
		path(): string;
		/**
		 * Parsed query string as an object — matches Ream's real
		 * `Request.qs()` contract (which returns
		 * `Record<string, unknown>`). The middleware pulls `exp` and
		 * `sig` by key; this is why the earlier string-returning
		 * variant silently bypassed verification in production.
		 */
		qs?(): Record<string, unknown>;
		header(name: string): string | undefined;
	};
	response: SignedRouteResponse;
}

export interface SignedRouteOptions {
	storage: StorageManager;
	/**
	 * The LocalDriver instance that produced the signatures. The
	 * middleware reads its HMAC secret via `getSigningSecret()` to
	 * recompute the expected signature.
	 */
	driver: LocalDriver;
	/**
	 * URL prefix for file serving. Defaults to — and must equal — the
	 * driver's `routeBasePath` (`driver.getRouteBasePath()`), which is what
	 * its URLs are built on. Configure the path on the driver; a different
	 * value here is refused at construction (`E_ARCHIVE_PREFIX_MISMATCH`)
	 * rather than producing a route that can never match a signed URL.
	 */
	prefix?: string;
}

type SignedRouteMiddleware = (
	ctx: SignedRouteHttpContext,
	next: () => Promise<void>,
) => Promise<void>;

/**
 * Build an async Ream middleware that verifies HMAC-signed URLs
 * generated by `LocalDriver.getSignedUrl`.
 */
export function createSignedRouteHandler(
	options: SignedRouteOptions,
): SignedRouteMiddleware {
	const prefix = options.driver.getRouteBasePath();
	if (
		options.prefix !== undefined &&
		options.prefix.replace(/\/+$/, "") !== prefix
	) {
		throw new E_ARCHIVE_PREFIX_MISMATCH([options.prefix, prefix]);
	}
	const secret = options.driver.getSigningSecret();
	if (secret === null) {
		throw new E_ARCHIVE_SIGNING_DISABLED([
			"createSignedRouteHandler: driver has no signingSecret configured. Pass { signingSecret } to LocalDriver first.",
		]);
	}
	const storage = options.storage;

	return async (ctx, next) => {
		if (ctx.request.method() !== "GET" && ctx.request.method() !== "HEAD") {
			return next();
		}

		const reqPath = ctx.request.path();
		if (!reqPath.startsWith(prefix)) return next();
		const after = reqPath[prefix.length];
		if (after !== undefined && after !== "/") return next();

		// Extract filePath from the URL — URL-DECODED so it matches
		// what the signer used. `LocalDriver.getSignedUrl` encodes each
		// path segment; we decode here before recomputing the HMAC.
		const encodedPath = reqPath.slice(prefix.length).replace(/^\//, "");
		if (encodedPath === "") return next();
		let decoded: string;
		try {
			decoded = decodeSegments(encodedPath);
		} catch {
			ctx.response.status(403).json({
				error: {
					code: "E_ARCHIVE_INVALID_SIGNATURE",
					message: "Malformed path",
				},
			});
			return;
		}
		// The key the signer signed is the normalised one; a path that does
		// not normalise (`..`, an encoded separator, a control character) names
		// nothing this route will serve.
		let filePath: string;
		try {
			filePath = normalizeKey(decoded);
		} catch {
			invalidKey(ctx);
			return;
		}

		// Pull `exp`/`sig` from the parsed query object — matches
		// Ream's `Request.qs()` contract (`Record<string, unknown>`).
		const qs = readQueryObject(ctx);
		if (qs.exp === undefined && qs.sig === undefined) {
			// No signature: this route still owns the prefix. Handing every
			// unsigned request on to `next()` let whatever was mounted behind —
			// a static server over the storage root, the obvious companion —
			// serve a PRIVATE file to anyone who left the query off. Visibility
			// is decided here: a public file is served, a private one refused,
			// and only a name that is not stored goes on to the next handler.
			//
			// NAMED DEVIATION: upstream answers this refusal with 401. It is a
			// 403 here, as every other refusal of this route already was: no
			// credential the client could add makes a private file servable
			// without a signature.
			let visibility: "public" | "private" | undefined;
			try {
				if (await storage.exists(filePath)) {
					visibility = await storage.getVisibility(filePath);
				}
			} catch (err) {
				// A name the disk refuses (a visibility marker's) is answered,
				// not thrown into the application's error handler.
				if (isKeyRefusal(err)) {
					invalidKey(ctx);
					return;
				}
				throw err;
			}
			if (visibility === undefined) return next();
			if (visibility !== "public") {
				ctx.response.status(403).json({
					error: { code: "E_ARCHIVE_ACCESS_DENIED", message: "Access denied" },
				});
				return;
			}
			return serve(ctx, filePath);
		}
		const expRaw = readStringParam(qs, "exp");
		const sigHex = readStringParam(qs, "sig");
		if (expRaw === null || sigHex === null) {
			// Half a signature, or one repeated into an array: a request that
			// tries to use a signature and cannot be verified is refused, never
			// downgraded to the unsigned path.
			ctx.response.status(403).json({
				error: {
					code: "E_ARCHIVE_INVALID_SIGNATURE",
					message: "Malformed signature",
				},
			});
			return;
		}

		// Validate sig shape up-front: 64 hex chars (sha256). Rejects
		// truncated/garbage sigs with a distinct code before we hit the
		// HMAC path. `Buffer.from(x, 'hex')` silently truncates invalid
		// input, so relying on length-after-decode is the wrong guard.
		if (!/^[a-f0-9]{64}$/.test(sigHex)) {
			ctx.response.status(403).json({
				error: {
					code: "E_ARCHIVE_INVALID_SIGNATURE",
					message: "Malformed signature",
				},
			});
			return;
		}

		// Strict canonical decimal: parseInt accepts trailing garbage,
		// signs, leading whitespace, etc., which would let multiple
		// `expRaw` query-strings collide on the same valid signature.
		const exp = Number.parseInt(expRaw, 10);
		if (!/^\d+$/.test(expRaw) || !Number.isFinite(exp)) {
			ctx.response.status(403).json({
				error: {
					code: "E_ARCHIVE_INVALID_SIGNATURE",
					message: "Malformed expiry",
				},
			});
			return;
		}

		// Response-header overrides travel in the query and are covered by
		// the signature. One present in a shape that cannot be verified
		// (repeated, or carrying a control character) is refused outright.
		const overrides: HeaderOverride[] = [];
		for (const [param] of HEADER_OVERRIDES) {
			const raw = qs[param];
			if (raw === undefined) continue;
			if (typeof raw !== "string" || !isHeaderValue(raw)) {
				ctx.response.status(403).json({
					error: {
						code: "E_ARCHIVE_INVALID_SIGNATURE",
						message: "Malformed header override",
					},
				});
				return;
			}
			if (raw !== "") overrides.push([param, raw]);
		}

		// Constant-time HMAC verification on the decoded path. The regex
		// check above already guarantees 32 bytes, so `timingSafeEqual`
		// cannot throw on a length mismatch here. Run BEFORE the expiry
		// check so the response time cannot leak whether a sig was valid
		// for an expired URL versus invalid for a fresh one.
		const expected = createHmac("sha256", secret)
			.update(signedPayload(filePath, exp, overrides))
			.digest();
		const provided = Buffer.from(sigHex, "hex");
		if (!timingSafeEqual(provided, expected)) {
			ctx.response.status(403).json({
				error: {
					code: "E_ARCHIVE_INVALID_SIGNATURE",
					message: "Invalid signature",
				},
			});
			return;
		}

		if (exp * 1000 <= Date.now()) {
			ctx.response.status(403).json({
				error: {
					code: "E_ARCHIVE_EXPIRED_SIGNATURE",
					message: "Signed URL expired",
				},
			});
			return;
		}

		// Signature verified — serve the file.
		return serve(ctx, filePath, overrides);
	};

	async function serve(
		ctx: SignedRouteHttpContext,
		filePath: string,
		overrides: readonly HeaderOverride[] = [],
	): Promise<void> {
		// Metadata first, the bytes only once they are known to be wanted: the
		// whole file used to be read into memory for every request, and a
		// client revalidating its copy got a full transfer each time.
		let metadata: Metadata;
		try {
			metadata = await storage.getMetadata(filePath);
		} catch (err) {
			if (isNotFound(err)) return notFound(ctx);
			throw new E_CANNOT_SERVE_FILE(err);
		}
		ctx.response.header("ETag", metadata.etag);
		ctx.response.header("Last-Modified", metadata.lastModified.toUTCString());
		ctx.response.header("Content-Type", metadata.contentType);
		// Signed overrides win over what the extension implies.
		for (const [param, value] of overrides) {
			const header = HEADER_OVERRIDES.find(([name]) => name === param)?.[1];
			if (header !== undefined) ctx.response.header(header, value);
		}
		if (
			matchesIfNoneMatch(ctx.request.header("if-none-match"), metadata.etag)
		) {
			ctx.response.status(304);
			return;
		}
		ctx.response.header("Content-Length", String(metadata.contentLength));
		if (ctx.request.method() === "HEAD") {
			ctx.response.status(200);
			return;
		}
		let body: NodeJS.ReadableStream;
		try {
			body = await storage.getStream(filePath);
		} catch (err) {
			// Deleted between the metadata read and the open.
			if (isNotFound(err)) return notFound(ctx);
			throw new E_CANNOT_SERVE_FILE(err);
		}
		ctx.response.status(200);
		await ctx.response.stream(body);
	}
}

/**
 * `err` and the errors it was caused by: a disk operation hands the driver's
 * error on as the `cause` of its own (`E_CANNOT_GET_METADATA` caused by
 * `E_ARCHIVE_NOT_FOUND`).
 */
function* causeChain(err: unknown): Generator<unknown> {
	const seen = new Set<unknown>();
	let current = err;
	while (current !== undefined && !seen.has(current)) {
		seen.add(current);
		yield current;
		current = current instanceof Error ? current.cause : undefined;
	}
}

function isNotFound(err: unknown): boolean {
	for (const error of causeChain(err)) {
		if (error instanceof E_ARCHIVE_NOT_FOUND) return true;
	}
	return false;
}

function notFound(ctx: SignedRouteHttpContext): void {
	ctx.response.status(404).json({
		error: { code: "E_ARCHIVE_NOT_FOUND", message: "File not found" },
	});
}

function invalidKey(ctx: SignedRouteHttpContext): void {
	ctx.response.status(403).json({
		error: { code: "E_ARCHIVE_INVALID_KEY", message: "Invalid path" },
	});
}

/**
 * Read the parsed query object from the HttpContext. Matches Ream's
 * `Request.qs()` contract (object). Returns an empty object when the
 * adapter does not expose `qs()` — in that rare case every request
 * will fall through to `next()`, which is the safe behaviour.
 */
function readQueryObject(ctx: SignedRouteHttpContext): Record<string, unknown> {
	if (typeof ctx.request.qs === "function") {
		return ctx.request.qs();
	}
	return {};
}

/** Read a query param as string, or return `null` if absent / non-string. */
function readStringParam(
	qs: Record<string, unknown>,
	key: string,
): string | null {
	const raw = qs[key];
	return typeof raw === "string" ? raw : null;
}

/**
 * Decode each URL-encoded path segment. Throws if any segment
 * contains invalid percent-escapes (`decodeURIComponent` throws on
 * malformed input), or decodes to a separator: the signer encodes each
 * segment on its own, so an encoded `/` or `\` never comes from a URL it
 * built, and would let one request segment pose as two.
 */
function decodeSegments(encodedPath: string): string {
	return encodedPath
		.split("/")
		.map((seg) => {
			const decoded = decodeURIComponent(seg);
			if (/[/\\]/.test(decoded)) {
				throw new Error("encoded separator in a path segment");
			}
			return decoded;
		})
		.join("/");
}
